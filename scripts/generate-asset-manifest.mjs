import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(scriptDir, "..");
const localizedRoot = path.join(root, "public", "assets", "ko");
const outputPath = path.join(root, "utils", "AssetManifest.generated.mjs");
const sharedRoot = path.join(root, "public", "assets");

if (!fs.existsSync(localizedRoot)) {
  throw new Error(`Korean asset directory not found: ${localizedRoot}`);
}

const paths = [];
const sharedPaths = [];
function walk(directory, target, skipKorean = false) {
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const fullPath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      if (skipKorean && fullPath === localizedRoot) continue;
      walk(fullPath, target, skipKorean);
    } else if (entry.isFile()) {
      target.push(path.relative(sharedRoot, fullPath).split(path.sep).join("/"));
    }
  }
}

walk(localizedRoot, paths);
walk(sharedRoot, sharedPaths, true);
// The manifest records actual localized files; directory policy lives in PathHelper.
const localizedPaths = paths;
localizedPaths.sort((a, b) => a.localeCompare(b, "en"));
sharedPaths.sort((a, b) => a.localeCompare(b, "en"));
paths.sort((a, b) => a.localeCompare(b, "en"));
if (paths.length === 0) {
  throw new Error(`No Korean asset files found under: ${localizedRoot}; refusing to write an empty manifest.`);
}

const content = `// Generated by scripts/generate-asset-manifest.mjs. Do not edit manually.
// Korean entries contain only unique localized files; shared entries resolve legacy Korean URLs.
export const KOREAN_ASSET_PATHS = new Set(
  ${JSON.stringify(localizedPaths.map(p => p.replace(/^ko\//i, "")), null, 2)}
);
export const SHARED_ASSET_PATHS = new Set(
  ${JSON.stringify(sharedPaths, null, 2)}
);
`;

const previous = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : null;
if (previous !== content) {
  fs.writeFileSync(outputPath, content, "utf8");
  console.log(`Updated asset manifest (${localizedPaths.length} unique Korean, ${sharedPaths.length} shared files).`);
} else {
  console.log(`Asset manifest is current (${localizedPaths.length} unique Korean, ${sharedPaths.length} shared files).`);
}
